// Build an SVG path ("M x y L x y ...") from a list of values, scaled to a width x height box.
function linePath(values: number[], w: number, h: number) {
  const max = Math.max(...values);
  return values
    .map((v, i) => `${i === 0 ? "M" : "L"}${(i / (values.length - 1)) * w} ${h - (v / max) * h}`)
    .join(" ");
}

